/* ── Render character at pixel position ──────────────────────────────── */

static void _ts_draw_char(TS_Canvas *c, int px, int py, char ch) {
    int idx = (int)ch - 32;
    if (idx < 0 || idx >= 95) return;
    uint32_t col = c->stroke_color;
    const unsigned char *glyph = _ts_font_8x16[idx];
    for (int row = 0; row < 16; row++) {
        unsigned char bits = glyph[row];
        for (int col_i = 0; col_i < 8; col_i++) {
            if (bits & (0x80 >> col_i))
                ts_pixel_blend(c, px + col_i, py + row, col);
        }
    }
}

